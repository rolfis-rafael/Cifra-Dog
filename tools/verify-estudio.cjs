const server = http.createServer((req, res) => {
    const pathname = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
    const resolved = path.resolve(root, '.' + pathname);
    if (resolved !== root && !resolved.startsWith(root + path.sep)) return res.writeHead(403).end();
    const file = path.extname(resolved) ? resolved : path.join(resolved, 'index.html');
    fs.readFile(file, (e, data) => { if (e) return res.writeHead(404).end(); res.writeHead(200, { 'Content-Type': (types[path.extname(file)] || 'application/octet-stream') + '; charset=utf-8' }); res.end(data); });
});
function wav() {
    const rate = 48000, seconds = 10, bytes = rate * seconds * 4, b = Buffer.alloc(44 + bytes);
    b.write('RIFF', 0); b.writeUInt32LE(36 + bytes, 4); b.write('WAVEfmt ', 8); b.writeUInt32LE(16, 16);
    b.writeUInt16LE(1, 20); b.writeUInt16LE(2, 22); b.writeUInt32LE(rate, 24); b.writeUInt32LE(rate * 4, 28); b.writeUInt16LE(4, 32); b.writeUInt16LE(16, 34); b.write('data', 36); b.writeUInt32LE(bytes, 40);
    for (let i = 0; i < rate * seconds; i++) { b.writeInt16LE(Math.round(8000 * Math.sin(2 * Math.PI * 440 * i / rate)), 44 + i * 4); b.writeInt16LE(Math.round(8000 * Math.sin(2 * Math.PI * 660 * i / rate)), 46 + i * 4); }
    return b;
}
